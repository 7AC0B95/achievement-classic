--[[
  criteria types used by Tracker.lua:
    LEVEL      - player reaches criteria.value
    DEATHLESS  - reach level criteria.value without any deaths
    MONEY      - accumulate looted copper to criteria.value (10000 = 1g)
    HEALTH     - survive combat after HP% <= criteria.threshold; value = times
    KILLS      - kill count; optional match = creature name substring
    QUESTS     - quest turn-in count
    ZONE       - visit a zone; match = zone name substring
    ZONES      - visit criteria.value unique zones
    DEATHS     - die criteria.value times
    CLASS      - be class (match = class file or name, e.g. "WARRIOR")
    RACE       - be race (match = race file or name)
    FACTION    - be Alliance or Horde (match = "Alliance" / "Horde")
    DUELS      - win criteria.value duels
    LOOT       - loot items; optional match = item name substring
    CRITS      - land criteria.value critical hits
    EMOTES     - use emotes; optional match filters emote text
    INSTANCE   - enter dungeon/raid; match = name, or value>1 = unique count
    REP        - reach standing with faction; match = faction, standing = "Honored"
    SKILL      - reach profession/skill rank; match = skill name, value = rank
    META       - complete criteria.value other achievements
    LOGIN      - log in (value usually 1)
    BUFF       - have a helpful aura; spellId = numeric id, optional match = name
                 Multi-criteria BUFF achievements require every listed buff at once.

  Optional achievement fields:
    hcOnly = true  - only tracked on Hardcore characters
    factionOnly    - "Alliance" / "Horde"; hidden and untracked for the other faction
]]

